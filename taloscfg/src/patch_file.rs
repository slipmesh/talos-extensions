/// What opens every patch file this tool writes.
pub const HEADER: &str =
    "# Generated by slipmesh-taloscfg from slipmesh.yaml - edit that file, not this one.\n";

/// The generated `ExtensionServiceConfig` document `name`, holding `files`.
fn render_extension_service_document(name: &str, files: Vec<ServiceFile>) -> Result<String> {
    sliplib_yaml::to_string(&ExtensionServiceConfig::new(name, files))
        .context("serializing an ExtensionServiceConfig document")
}

/// The `patch` documents in `patches` that add to the generated document `name`, merged - taken
/// out of `patches`, since Talos takes one document per name and the generated one carries them.
fn take_added(patches: &mut Vec<HostDocument>, name: &str) -> Option<HostDocument> {
    let identity = format!("ExtensionServiceConfig/{name}");
    let index = patches.iter().position(|p| p.identity == identity)?;
    Some(patches.remove(index))
}

/// The files `added` adds to a generated document, as written.
fn added_files(added: Option<&HostDocument>) -> Vec<ServiceFile> {
    added
        .and_then(|added| added.value.get("configFiles"))
        .and_then(sliplib_yaml::Value::as_sequence)
        .into_iter()
        .flatten()
        .cloned()
        .map(ServiceFile::Added)
        .collect()
}

/// The files of the `nftables` document: the template, its config, and the files `added`.
fn nftables_config_files(
    template: &str,
    values: &Values,
    added: Vec<ServiceFile>,
) -> Result<Vec<ServiceFile>> {
    let generated = [
        ConfigFile {
            mount_path: Service::Firewall.mount_path().to_owned(),
            content: template.to_owned(),
        },
        ConfigFile {
            mount_path: nftables::template::CONFIG_PATH.to_owned(),
            content: sliplib_yaml::to_string(values)?,
        },
    ];
    Ok(generated
        .into_iter()
        .map(ServiceFile::Generated)
        .chain(added)
        .collect())
}

/// Refuses a router template the node would fail on: one that does not compile, reads a variable
/// the daemon does not supply, or fails to render this node's config and values.
fn validate_router_template(template: &str, cfg: &RouterConfig, values: &Values) -> Result<()> {
    let template = router::bird_conf::compile(template.to_owned())?;
    router::bird_conf::render_config(&template, cfg, values, &[])?;
    Ok(())
}

/// Refuses a firewall template that would fail on the node. The interfaces stand in as their own
/// names; the text is not kept.
fn validate_firewall_template(template: &str, values: &Values) -> Result<()> {
    use nftables::template::{DEFAULT_ROUTE_IPV4, DEFAULT_ROUTE_IPV6};
    let template = nftables::template::compile(template.to_owned())?;
    let interfaces = [DEFAULT_ROUTE_IPV4, DEFAULT_ROUTE_IPV6]
        .map(|name| (name, name.to_owned()))
        .into();
    nftables::template::render(&template, &interfaces, values)?;
    Ok(())
}

/// `router.yaml`: the daemon's config, then the values of its template.
#[derive(serde::Serialize)]
struct RouterFile<'a> {
    #[serde(flatten)]
    daemon: &'a RouterDaemonConfig,
    #[serde(flatten)]
    values: &'a Values,
}

/// The documents of `patches`, `annotations` put into their `KubeNodeConfig`, or into a new one
/// when they have none: Talos takes one.
fn publish_annotations(patches: Vec<HostDocument>, annotations: Mapping) -> Vec<Value> {
    let given = patches
        .iter()
        .position(|p| p.identity == talos::KUBE_NODE_CONFIG);
    let mut documents: Vec<Value> = patches.into_iter().map(|patch| patch.value).collect();
    let index = given.unwrap_or_else(|| {
        documents.push(talos::kube_node_config());
        documents.len() - 1
    });
    documents[index] = talos::annotate(std::mem::take(&mut documents[index]), annotations);
    documents
}

/// The templates a node gets: of those that reach it, the last by rank for each daemon, or the
/// daemon's reference where none does.
struct Templates {
    router: String,
    firewall: String,
}

impl Templates {
    /// Refuses a template the node gets that its daemon would fail on. A router template is
    /// rendered with `router`, the node's config, and each with `values`, the node's.
    fn of(files: &File, host: &str, router: &RouterConfig, values: &Values) -> Result<Self> {
        let mut router_template = None;
        let mut firewall_template = None;
        for document in files.templates_for(host) {
            let template: Template = document.read()?;
            let last = match template.daemon {
                Service::Router => &mut router_template,
                Service::Firewall => &mut firewall_template,
            };
            *last = Some((document, template.content));
        }
        Ok(Self {
            router: checked(router_template, Service::Router, |content| {
                validate_router_template(content, router, values)
            })?
            .unwrap_or_else(|| Service::Router.reference().to_owned()),
            firewall: checked(firewall_template, Service::Firewall, |content| {
                validate_firewall_template(content, values)
            })?
            .unwrap_or_else(|| Service::Firewall.reference().to_owned()),
        })
    }
}

/// The content of `last`, the `service` template a node gets, once `check` accepts it.
fn checked(
    last: Option<(&AimedDocument, String)>,
    service: Service,
    check: impl FnOnce(&str) -> Result<()>,
) -> Result<Option<String>> {
    last.map(|(document, content)| {
        check(&content)
            .with_context(|| format!("{}: the {service} template is invalid", document.aim()))?;
        Ok(content)
    })
    .transpose()
}

/// The patch file of `host`, a node of `talos`, as the text written to disk. A refusal names the
/// node: one of computing its configs does already.
pub fn render(
    files: &File,
    network: &Mesh<'_>,
    settings: &TalosSettings,
    host: &str,
) -> Result<String> {
    let NodeConfigs { awg, router } = node_configs(network, host)?;
    let loopback = router.node.loopback_addresses.ipv4.0.addr();
    let metrics = &settings.metrics;
    let awg_cfg = AwgDaemonConfig {
        mesh: awg,
        metrics: listener(loopback, metrics.mesh.as_ref()),
    };
    let router_cfg = RouterDaemonConfig {
        mesh: router,
        metrics: listener(loopback, metrics.router.as_ref()),
    };
    render_node(files, network, host, awg_cfg, router_cfg).with_context(|| format!("node {host:?}"))
}

fn listener(loopback: Ipv4Addr, listener: Option<&Listener>) -> Option<MetricsConfig> {
    listener.map(|listener| MetricsConfig {
        listen: (loopback, listener.port.get()).into(),
    })
}

fn render_node(
    files: &File,
    network: &Mesh<'_>,
    host: &str,
    awg_cfg: AwgDaemonConfig,
    router_cfg: RouterDaemonConfig,
) -> Result<String> {
    let values = Values {
        classes: network.network().routing.classes.clone(),
        vars: sliplib_yaml::from_value(files.vars_for(host))?,
    };
    let templates = Templates::of(files, host, &router_cfg.mesh, &values)?;

    let mut patches = patches::for_host(files, host)?;
    let awg = std::iter::once(ServiceFile::Generated(ConfigFile {
        mount_path: AWG_CONFIG_PATH.to_owned(),
        content: sliplib_yaml::to_string(&awg_cfg)?,
    }))
    .chain(added_files(take_added(&mut patches, "awg").as_ref()))
    .collect();
    let router = [
        ConfigFile {
            mount_path: ROUTER_CONFIG_PATH.to_owned(),
            content: sliplib_yaml::to_string(&RouterFile {
                daemon: &router_cfg,
                values: &values,
            })?,
        },
        ConfigFile {
            mount_path: Service::Router.mount_path().to_owned(),
            content: templates.router,
        },
    ]
    .into_iter()
    .map(ServiceFile::Generated)
    .chain(added_files(
        take_added(&mut patches, Service::Router.name()).as_ref(),
    ))
    .collect();
    let mut generated = vec![
        render_extension_service_document("awg", awg)?,
        render_extension_service_document(Service::Router.name(), router)?,
    ];
    let nftables_added = added_files(take_added(&mut patches, Service::Firewall.name()).as_ref());
    generated.push(render_extension_service_document(
        Service::Firewall.name(),
        nftables_config_files(&templates.firewall, &values, nftables_added)?,
    )?);

    let node = network.node(host)?;
    let patches = publish_annotations(
        patches,
        crate::annotations::for_node(&crate::annotations::Values {
            interface_prefix: network.interface_prefix(),
            classes: &network.network().routing.classes,
            endpoint: node
                .underlay()
                .and_then(|underlay| underlay.endpoint.as_ref())
                .map(|endpoint| endpoint.host()),
            mesh_mtu: sliplib_mesh::mtu::mesh_mtu(network)?,
        }),
    );
    let patches = patches
        .iter()
        .map(|patch| sliplib_yaml::to_string(patch).context("serializing a patch document"))
        .collect::<Result<Vec<String>>>()?;

    let rules = talos::rules(network.network())
        .map(|(_, class, _, rule)| {
            sliplib_yaml::to_string(&talos::RoutingRuleConfig::new(class, rule))
                .context("serializing a RoutingRuleConfig document")
        })
        .collect::<Result<Vec<String>>>()?;

    Ok(format!(
        "{HEADER}{}",
        sliplib_yaml::join(&[patches, generated, rules].concat())
    ))
}

