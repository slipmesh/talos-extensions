    /// `SLIPMESH` with a `router` template document for each of `templates`, its aim and its
    /// text.
    fn with_router_files(templates: &[(&str, &str)]) -> String {
        let mut raw = SLIPMESH.to_string();
        for (aim, template) in templates {
            raw.push_str(&format!(
                "---\nslipmesh:\n  kind: template\n  platform: talos\n{aim}daemon: router\nbase: \
                 {BASE}\ncontent: {template:?}\n"
            ));
        }
        raw
    }

    fn render_raw(raw: &str, host: &str) -> Result<String> {
        let files = File::parse(raw).unwrap();
        let network = Mesh::of(&files).unwrap();
        render(&files, &network, &TalosSettings::of(&files).unwrap(), host)
    }

    fn router_files(patch: &str) -> Vec<(String, String)> {
        let documents: Vec<sliplib_yaml::Value> = documents(patch)
            .into_iter()
            .filter(|value| value["kind"] == "ExtensionServiceConfig" && value["name"] == "router")
            .collect();
        assert_eq!(documents.len(), 1, "one router document: {patch}");
        documents[0]["configFiles"]
            .as_sequence()
            .unwrap()
            .iter()
            .map(|f| {
                (
                    f["mountPath"].as_str().unwrap().to_string(),
                    f["content"].as_str().unwrap().to_string(),
                )
            })
            .collect()
    }

    /// A `patch` adding the file `extra` to the generated document `name`, for every node.
    fn adding_to(name: &str) -> String {
        format!(
            "---\nslipmesh: {{kind: patch, platform: talos}}\napiVersion: v1alpha1\nkind: \
             ExtensionServiceConfig\nname: {name}\nconfigFiles:\n  - mountPath: \
             /etc/talos-extensions/extra\n    content: x\n"
        )
    }

